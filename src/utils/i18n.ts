export function getMonthName(month: number, lang: Language): string {
  const idx = Math.max(0, Math.min(11, month - 1));
  return lang === 'bn' ? MONTHS_BN[idx] : MONTHS_EN[idx];
}

export function getCategoryLabel(cat: IncomeCategory | ExpenseCategory, lang: Language): string {
  return CATEGORY_LABELS[cat]?.[lang] ?? cat;
}

export function getPaymentLabel(pm: PaymentMethod, lang: Language): string {
  return PAYMENT_LABELS[pm]?.[lang] ?? pm;
}

